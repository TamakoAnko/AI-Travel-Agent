def test_plan_is_valid():
    assert plan_is_valid(VALID, 5)


def test_plan_missing_budget():
    assert not plan_is_valid(VALID.split("## 预算汇总")[0], 5)


def test_plan_missing_day():
    broken = VALID.replace("## DAY 3", "## 第三天")
    assert not plan_is_valid(broken, 5)


def test_heuristic_brief():
    brief = heuristic_brief("从上海出发，去东京玩4天，预算1.2万，喜欢动漫")
    assert brief.origin == "上海"
    assert brief.destination == "东京"
    assert brief.days == 4
    assert brief.budget == 12000
